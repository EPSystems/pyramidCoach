// Generates supabase/seed.sql from lib/knowledge (single source of truth). Idempotent upserts.
// Run: pnpm seed:gen
import { writeFileSync } from 'node:fs';
import { EXERCISE_SEEDS } from '../lib/knowledge/exercises';
import { SPORT_SEEDS } from '../lib/knowledge/sports';
import { RULE_LIST } from '../lib/knowledge/rules';
import { MUSCLE_SEEDS, PATTERN_SEEDS } from '../lib/knowledge/muscles';

const q = (s: string | null | undefined) => (s == null ? 'null' : `'${s.replace(/'/g, "''")}'`);
const arr = (xs: string[]) => `array[${xs.map(q).join(',')}]::text[]`;
const exId = (slug: string) => `md5('ex:' || ${q(slug)})::uuid`;

const ownerEmail = process.env.OWNER_EMAIL ?? 'emildermendjiev9@gmail.com';
const out: string[] = ['-- GENERATED by scripts/gen-seed.ts. Do not edit by hand.', 'begin;'];

out.push(`insert into public.app_config (key, value) values ('owner_email', ${q(ownerEmail)}) on conflict (key) do update set value = excluded.value;`);

for (const m of MUSCLE_SEEDS) {
  out.push(
    `insert into public.muscles (id, name, region, tracked, body_map_side) values (${q(m.id)}, ${q(m.name)}, ${q(m.region)}, ${m.tracked}, ${arr(m.sides)}) ` +
      `on conflict (id) do update set name = excluded.name, region = excluded.region, tracked = excluded.tracked, body_map_side = excluded.body_map_side;`,
  );
}
for (const p of PATTERN_SEEDS) {
  out.push(`insert into public.movement_patterns (id, name) values (${q(p.id)}, ${q(p.name)}) on conflict (id) do update set name = excluded.name;`);
}
EXERCISE_SEEDS.forEach((e, i) => {
  out.push(
    `insert into public.exercises (id, slug, name, pattern_id, category, equipment, is_main_lift, main_lift_key, long_length_bias, unilateral, axial_load, impact_lower_body, default_increment_kg, cues, mistakes, substitutions, slot_tags, popularity) values (` +
      `${exId(e.slug)}, ${q(e.slug)}, ${q(e.name)}, ${q(e.pattern)}, ${q(e.category)}, ${arr(e.equipment)}, ${!!e.main}, ${q(e.main ?? null)}, ${!!e.long}, ${!!e.unilateral}, ${!!e.axial}, ${!!e.impact}, ${e.increment ?? 'null'}, ` +
      `${arr(e.cues)}, ${arr(e.mistakes)}, ${arr(e.subs)}, ${arr(e.tags)}, ${i}) on conflict (slug) do update set name = excluded.name, pattern_id = excluded.pattern_id, category = excluded.category, ` +
      `equipment = excluded.equipment, is_main_lift = excluded.is_main_lift, main_lift_key = excluded.main_lift_key, long_length_bias = excluded.long_length_bias, unilateral = excluded.unilateral, ` +
      `axial_load = excluded.axial_load, impact_lower_body = excluded.impact_lower_body, default_increment_kg = excluded.default_increment_kg, cues = excluded.cues, mistakes = excluded.mistakes, substitutions = excluded.substitutions, slot_tags = excluded.slot_tags, popularity = excluded.popularity;`,
  );
  out.push(`delete from public.exercise_muscles where exercise_id = ${exId(e.slug)};`);
  for (const m of e.primary) out.push(`insert into public.exercise_muscles (exercise_id, muscle_id, role) values (${exId(e.slug)}, ${q(m)}, 'primary');`);
  for (const m of e.secondary) out.push(`insert into public.exercise_muscles (exercise_id, muscle_id, role) values (${exId(e.slug)}, ${q(m)}, 'secondary');`);
});
for (const s of SPORT_SEEDS) {
  out.push(
    `insert into public.sports (id, name, lower_body_load, upper_body_load, eccentric_impact, conditioning, muscles_stressed, default_minutes, notes) values (` +
      `${q(s.id)}, ${q(s.name)}, ${s.lower}, ${s.upper}, ${s.impact}, ${s.conditioning}, ${arr(s.muscles)}, ${s.defaultMinutes}, ${q(s.notes)}) on conflict (id) do update set ` +
      `name = excluded.name, lower_body_load = excluded.lower_body_load, upper_body_load = excluded.upper_body_load, eccentric_impact = excluded.eccentric_impact, ` +
      `conditioning = excluded.conditioning, muscles_stressed = excluded.muscles_stressed, default_minutes = excluded.default_minutes, notes = excluded.notes;`,
  );
}
for (const r of RULE_LIST) {
  out.push(
    `insert into public.rule_sources (id, source, page, summary) values (${q(r.id)}, ${q(r.source)}, ${q(r.page ?? null)}, ${q(r.summary)}) ` +
      `on conflict (id) do update set source = excluded.source, page = excluded.page, summary = excluded.summary;`,
  );
}
out.push('commit;', '');
writeFileSync('supabase/seed.sql', out.join('\n'));
console.log(`seed.sql: ${EXERCISE_SEEDS.length} exercises, ${SPORT_SEEDS.length} sports, ${RULE_LIST.length} rules, ${MUSCLE_SEEDS.length} muscles`);
